/**
 * ⚠⚠ THE MODEL ENUMERATION QUERY — the one query that answers *"what elements are actually in this
 * model?"*, and the project-wide quantity roll-up built on it (`P5_step6A_enumeration_design.md`).
 *
 * **Why it exists.** The 2026-07-25 adversarial sweep (Entry 57, finding 2) measured that **the model
 * cannot be enumerated**: `scene.elements` is the AUTHORED ROWS, which is not the set of real elements.
 * Three separate consumers — the project quantity roll-up, the schedules (D58), and the Clean Delta
 * exporter — each need the same walk, and each had been writing it by hand. The plan's own instruction:
 *
 *   > *"BUILD THE PROJECT-WIDE QUANTITIES PATH, AND **MAKE IT A COMMAND/QUERY, NOT A LOOP EVERY
 *   > CONSUMER REWRITES**"* — `v1.0.0_imp_plan.md`, P5 exit criteria.
 *
 * ⚠ **This is additive and touches nothing frozen** (D19, `core_logic.md` rule 5). No stored byte, no
 * `SCENE_SCHEMA_VERSION` bump, no new field on `PartQuantity` — the LBS address rides on the *row*.
 *
 * ⚠⚠ **THE MEASUREMENT THAT SHAPED IT** (design §1, real OCCT, real `@bunyan/types`): a building of
 * **3 authored rows** holds **19 real elements**; 15 carry their own parts and **4 carry none**. The
 * naive `for (id of Object.keys(scene.elements)) await doc.quantities(id)` counted **2** and threw.
 *
 * ⚠⚠ AND THE FINDING THAT WIDENED THE RULE — *"skip voids"* IS THE WRONG RULE. Both `review_P4.md`
 * (2026-07-14) and Entry 57 named **the Opening** as what kills the loop (*"a void has no parts"*).
 * Measured, the loop dies on the **CURTAIN WALL** — a **pure composite** parent, which has no own parts
 * BY DESIGN (`curtainwall.ts`: *"NO buildGeometry — a pure composite"*). A rule written to skip voids
 * specifically would have shipped green and still crashed on the very element D59 was built to prove.
 * The honest rule is **"an element with no OWN parts contributes no quantity rows"**, and it has two
 * populations. *(The ⓙ door is in neither — it has a leaf and a frame, and it is measured.)*
 */

